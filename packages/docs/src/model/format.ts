/**
 * Paragraph attrs → CSS, shared by the editor's renderHTML and static renders
 * (headers on every page, version previews). Mirrors `ppr_css` in the codec.
 */

export interface ParagraphAttrs {
  pPr: string | null;
  styleId: string | null;
  align: 'left' | 'center' | 'right' | 'justify' | null;
  spacing: { before?: number; after?: number; line?: number; lineRule?: string } | null;
  ind: { left?: number; right?: number; firstLine?: number; hanging?: number } | null;
  numId: number | null;
  ilvl: number;
  outline: number | null;
  css: string | null;
  sectionBreak: boolean;
  checked: boolean | null;
}

const pt = (tw: number) => `${+(tw / 20).toFixed(2)}pt`;

/** Word's "auto" line spacing (240 = single) as a CSS line-height. */
export const lineHeightFor = (line: number) => +((line / 240) * 1.15).toFixed(3);

export function paragraphCss(a: Partial<ParagraphAttrs>): string {
  const out: string[] = [];
  if (a.align) out.push(`text-align:${a.align}`);
  const s = a.spacing;
  if (s) {
    if (typeof s.before === 'number') out.push(`margin-top:${pt(s.before)}`);
    if (typeof s.after === 'number') out.push(`margin-bottom:${pt(s.after)}`);
    if (typeof s.line === 'number') {
      out.push(!s.lineRule || s.lineRule === 'auto' ? `line-height:${lineHeightFor(s.line)}` : `line-height:${pt(s.line)}`);
    }
  }
  const i = a.ind;
  if (i) {
    if (typeof i.left === 'number') out.push(`margin-left:${pt(i.left)}`);
    if (typeof i.right === 'number') out.push(`margin-right:${pt(i.right)}`);
    if (typeof i.hanging === 'number' && i.hanging) out.push(`text-indent:${pt(-i.hanging)}`);
    else if (typeof i.firstLine === 'number') out.push(`text-indent:${pt(i.firstLine)}`);
  }
  if (a.css) out.push(sanitizeDeclarations(a.css));
  return out.join(';');
}


/**
 * Display CSS comes from documents and collaborators: keep declarations that
 * cannot fetch anything or escape their rule (no url(), @import, expressions).
 */
export function sanitizeDeclarations(css: string): string {
  return css
    .split(';')
    .filter((d) => d.trim() && !/url\s*\(|expression\s*\(|@import|javascript:|[<>{}\\]/i.test(d))
    .join(';');
}

/** Same for a whole stylesheet (the styles CSS generated by the codec). */
export function sanitizeStylesheet(css: string): string {
  return css.replace(/url\s*\([^)]*\)/gi, 'none').replace(/@import[^;]*;?/gi, '').replace(/expression\s*\(/gi, '(').replace(/<\/?style/gi, '');
}

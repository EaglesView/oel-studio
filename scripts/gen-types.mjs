#!/usr/bin/env node
/**
 * Regenerates the TypeScript contract types from the Rust crates (ts-rs) into
 * `packages/engine/src/generated/<crate>/`, plus an `index.ts` per folder.
 * Every crate with a `ts` feature takes part. Runs before `npm run typecheck`,
 * so renaming a field in Rust breaks the TypeScript that uses it.
 */
import { spawnSync } from 'node:child_process';
import { readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const outDir = join(root, 'packages', 'engine', 'src', 'generated');

const crates = readdirSync(join(root, 'crates')).filter((c) =>
  /^\s*ts\s*=/m.test(readFileSync(join(root, 'crates', c, 'Cargo.toml'), 'utf8')),
);
for (const d of readdirSync(outDir, { withFileTypes: true })) if (d.isDirectory()) rmSync(join(outDir, d.name), { recursive: true });

const features = crates.map((c) => `${c}/ts`).join(',');
const r = spawnSync('cargo', ['test', '--quiet', '--workspace', '--features', features, '--lib', 'export_bindings'], { cwd: root, stdio: ['ignore', 'ignore', 'inherit'] });
if (r.status !== 0) process.exit(r.status ?? 1);

for (const d of readdirSync(outDir, { withFileTypes: true })) {
  if (!d.isDirectory()) continue;
  const names = readdirSync(join(outDir, d.name))
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts')
    .map((f) => f.slice(0, -3))
    .sort();
  const lines = names.map((n) => `export * from './${n}';`);
  writeFileSync(join(outDir, d.name, 'index.ts'), `// Generated by scripts/gen-types.mjs from the Rust crates (ts-rs). Do not edit.\n${lines.join('\n')}\n`);
}
